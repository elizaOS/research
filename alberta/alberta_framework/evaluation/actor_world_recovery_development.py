"""Deterministic L0 actor/world retention and matched-recovery scaffold.

This module localizes retention in one uninterrupted online ``A -> B`` prefix
followed by three counterfactual, zero-environment A-recovery branches.  A fixed
evaluator action schedule visits both actions in the real online prefix, while
the learner receives only the observation, chosen action, and subsequently
revealed one-step outcome.  World and value knowledge use fixed-size
per-context/action running means; the actor is a shared linear softmax policy.
The asymmetric function classes are intentional and reported as a limitation:
this is a mechanism localizer, not an architecture comparison or a real online
A recurrence.

After B interference, the frozen world/value state mints one two-action A
dataset.  Every model-generated field is checked against the deterministic
real anchor.  Policy gradient and dream imitation consume byte-identical
imagined starts, transitions, and returns.  A separately evaluator-attested
competent-real label batch has the same sample count and update budget.  Every
arm starts from the exact same post-B actor state and feeds one of three
equal-budget analytic objectives:

* expected-return policy gradient under the current policy;
* graded positive-return supervised dream imitation;
* unit-weight competent-real cloning as a source/control arm.

Only actor parameters change during recovery.  The report contains raw
descriptive probes, exact logical work and serialization accounting, timing,
source/config/state/dataset/trajectory hashes, and a deterministic
reconstruction validator.  It has no thresholds, verdict, output writer,
artifact authority, benchmark authority, evidence claim, or promotion path.
"""

